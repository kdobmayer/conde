-- The board schema, Postgres dialect of the SQLite schema in db.rs.
-- Text is COLLATE "C" so every ORDER BY matches SQLite's byte order whatever
-- the database's default collation. *_seq identity columns stand in for
-- SQLite's rowid where insertion order matters.

CREATE TABLE users(
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL UNIQUE
);
CREATE TABLE hosts(
    host_id TEXT COLLATE "C" PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id)
);
CREATE TABLE device_credentials(
    token_digest TEXT COLLATE "C" PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    host_id TEXT COLLATE "C" NOT NULL REFERENCES hosts(host_id),
    revoked_at TEXT,
    label TEXT,
    created_at TEXT
);
CREATE INDEX credentials_by_host ON device_credentials(host_id);
CREATE TABLE agents(
    agent_id TEXT COLLATE "C" PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(user_id),
    name_lower TEXT COLLATE "C" NOT NULL,
    display TEXT,
    address_kind TEXT COLLATE "C" CHECK (address_kind IN ('claude', 'codex', 'human')),
    address_target TEXT COLLATE "C",
    host_id TEXT COLLATE "C",
    binding_version BIGINT NOT NULL DEFAULT 0,
    pinned_address TEXT COLLATE "C",
    UNIQUE (owner_id, name_lower)
);
CREATE INDEX agents_by_address ON agents(address_kind, address_target, host_id);
CREATE TABLE channels(
    channel_id TEXT COLLATE "C" PRIMARY KEY,
    name_lower TEXT COLLATE "C" NOT NULL UNIQUE,
    created_by TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id)
);
CREATE TABLE messages(
    commit_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id TEXT COLLATE "C" NOT NULL UNIQUE,
    sender_agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id),
    recipient_agent_id TEXT COLLATE "C" REFERENCES agents(agent_id),
    channel_id TEXT COLLATE "C" REFERENCES channels(channel_id),
    text TEXT NOT NULL,
    reply_to TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL,
    CHECK ((recipient_agent_id IS NULL) <> (channel_id IS NULL))
);
CREATE INDEX messages_by_recipient ON messages(recipient_agent_id, commit_seq);
CREATE INDEX messages_by_channel ON messages(channel_id, commit_seq);
CREATE INDEX messages_by_sender ON messages(sender_agent_id, commit_seq);
CREATE TABLE attachments(
    attachment_id TEXT COLLATE "C" PRIMARY KEY,
    message_id TEXT COLLATE "C" NOT NULL REFERENCES messages(message_id),
    filename TEXT COLLATE "C" NOT NULL,
    bytes BYTEA NOT NULL,
    size BIGINT NOT NULL
);
CREATE INDEX attachments_by_message ON attachments(message_id);
CREATE TABLE memberships(
    channel_id TEXT COLLATE "C" NOT NULL REFERENCES channels(channel_id),
    agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id),
    read_seq BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (channel_id, agent_id)
);
CREATE INDEX memberships_by_agent ON memberships(agent_id);
CREATE TABLE dm_read(
    message_id TEXT COLLATE "C" NOT NULL REFERENCES messages(message_id),
    agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id),
    read_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (message_id, agent_id)
);
CREATE TABLE reactions(
    message_id TEXT COLLATE "C" NOT NULL REFERENCES messages(message_id),
    actor_id TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id),
    emoji TEXT COLLATE "C" NOT NULL,
    present BOOLEAN NOT NULL,
    PRIMARY KEY (message_id, actor_id, emoji)
);
CREATE TABLE idempotency(
    actor_id TEXT COLLATE "C" NOT NULL,
    op TEXT COLLATE "C" NOT NULL,
    key TEXT COLLATE "C" NOT NULL,
    request_hash TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (actor_id, op, key)
);
CREATE TABLE notifications(
    notification_id TEXT COLLATE "C" PRIMARY KEY,
    notification_seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    message_id TEXT COLLATE "C" NOT NULL REFERENCES messages(message_id),
    recipient_agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents(agent_id),
    kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('dm', 'mention', 'post')),
    binding_version BIGINT NOT NULL,
    status TEXT COLLATE "C" NOT NULL,
    next_attempt_at BIGINT NOT NULL
);
CREATE INDEX notifications_due ON notifications(status, next_attempt_at);
CREATE TABLE attempts(
    attempt_id TEXT COLLATE "C" PRIMARY KEY,
    attempt_seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    notification_id TEXT COLLATE "C" NOT NULL REFERENCES notifications(notification_id),
    bridge_instance TEXT COLLATE "C" NOT NULL,
    target_binding_version BIGINT NOT NULL,
    last_event_seq BIGINT NOT NULL DEFAULT 0,
    status TEXT COLLATE "C" NOT NULL,
    reason TEXT,
    host_id TEXT COLLATE "C",
    text TEXT
);
CREATE INDEX attempts_by_notification ON attempts(notification_id, attempt_seq);
CREATE INDEX attempts_by_instance ON attempts(bridge_instance, status);
CREATE TABLE bridge_instances(
    instance TEXT COLLATE "C" PRIMARY KEY,
    host_id TEXT COLLATE "C" NOT NULL,
    state TEXT COLLATE "C" NOT NULL CHECK (state IN ('active', 'fenced')),
    updated_at TEXT NOT NULL
);
CREATE INDEX bridge_instances_by_host ON bridge_instances(host_id, state);
CREATE TABLE endpoints(
    host_id TEXT COLLATE "C" NOT NULL,
    kind TEXT COLLATE "C" NOT NULL,
    target TEXT COLLATE "C" NOT NULL,
    bridge_instance TEXT COLLATE "C" NOT NULL,
    seen_at TEXT NOT NULL,
    PRIMARY KEY (host_id, kind, target)
);
